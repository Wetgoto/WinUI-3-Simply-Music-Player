param(
    [string]$Configuration = 'Release'
)

$ErrorActionPreference = 'Stop'

$projectRoot = Split-Path $PSScriptRoot -Parent
$project = Join-Path $projectRoot 'Music.csproj'
$staging = Join-Path $projectRoot '.publish'
$destinationExe = Join-Path $projectRoot 'Music.exe'
$configDirectory = Join-Path $projectRoot 'config'

if (-not (Test-Path -LiteralPath $project)) {
    throw "Project not found: $project"
}

if (Test-Path -LiteralPath $staging) {
    Remove-Item -LiteralPath $staging -Recurse -Force
}

$restoreArguments = @(
    'restore', $project,
    '-r', 'win-x64',
    '-p:Platform=x64',
    '-p:SelfContained=true',
    '-p:NuGetAudit=false'
)

& dotnet @restoreArguments
if ($LASTEXITCODE -ne 0) {
    $localPackages = Join-Path $env:USERPROFILE '.nuget\packages'
    if (Test-Path -LiteralPath $localPackages) {
        Write-Host 'Online restore failed, retrying from the local NuGet cache...'
        $restoreArguments += @('--source', $localPackages)
        & dotnet @restoreArguments
    }

    if ($LASTEXITCODE -ne 0) {
        throw "dotnet restore failed with exit code $LASTEXITCODE"
    }
}

$publishArguments = @(
    'publish', $project,
    '-c', $Configuration,
    '-r', 'win-x64',
    '--self-contained', 'true',
    '--no-restore',
    '-p:Platform=x64',
    '-p:SelfContained=true',
    '-p:PublishSingleFile=true',
    '-p:EnableMsixTooling=true',
    '-p:IncludeNativeLibrariesForSelfExtract=true',
    '-p:IncludeAllContentForSelfExtract=true',
    '-p:EnableCompressionInSingleFile=true',
    '-p:DebugType=None',
    '-p:DebugSymbols=false',
    '-p:NuGetAudit=false',
    '-o', $staging
)

& dotnet @publishArguments
if ($LASTEXITCODE -ne 0) {
    throw "dotnet publish failed with exit code $LASTEXITCODE"
}

$publishedExe = Join-Path $staging 'Music.exe'
if (-not (Test-Path -LiteralPath $publishedExe)) {
    throw "Published Music.exe not found at $publishedExe"
}

New-Item -ItemType Directory -Path $configDirectory -Force | Out-Null
Copy-Item -LiteralPath $publishedExe -Destination $destinationExe -Force
Remove-Item -LiteralPath $staging -Recurse -Force

# Keep the project folder tidy; these are regenerated by the next publish/build.
foreach ($buildFolder in @('bin', 'obj')) {
    $path = Join-Path $projectRoot $buildFolder
    if (Test-Path -LiteralPath $path) {
        Remove-Item -LiteralPath $path -Recurse -Force
    }
}

$sizeMb = [math]::Round((Get-Item $destinationExe).Length / 1MB, 1)
Write-Host "Published: $destinationExe ($sizeMb MB)"
Write-Host "Playlist config: $(Join-Path $configDirectory 'playlist.json')"
