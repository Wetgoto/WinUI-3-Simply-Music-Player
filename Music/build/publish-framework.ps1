param(
    [string]$Configuration = 'Release'
)

# Publishes a framework-dependent, multi-file build: Music.exe plus its DLLs
# and resource folders. The app starts straight from Music.exe, with no
# single-file self-extraction and no launcher script.
#
# Music.exe loads the Windows App SDK natives, the .deps.json, .runtimeconfig.json
# and the .pri resources from the folder that contains the executable, so those
# files cannot be moved into subfolders (loading them from anywhere else fails
# with "Unable to load DLL 'Microsoft.WindowsAppRuntime.dll'"). What can stay out
# of the way is already grouped: Assets\ (icons), language\ (other UI languages),
# Microsoft.UI.Xaml\ and NpuDetect\.
$ErrorActionPreference = 'Stop'

$projectRoot = Split-Path $PSScriptRoot -Parent
$project = Join-Path $projectRoot 'Music.csproj'
$staging = Join-Path $projectRoot '.publish-framework'
$output = Join-Path $projectRoot 'dist'

if (-not (Test-Path -LiteralPath $project)) {
    throw "Project not found: $project"
}

# Intermediates from an earlier publish can leak stale files into the output.
foreach ($folder in @('bin', 'obj')) {
    $path = Join-Path $projectRoot $folder
    if (Test-Path -LiteralPath $path) {
        Remove-Item -LiteralPath $path -Recurse -Force
    }
}

foreach ($path in @($staging, $output)) {
    if (Test-Path -LiteralPath $path) {
        Remove-Item -LiteralPath $path -Recurse -Force
    }
}

$restoreArguments = @(
    'restore', $project,
    '-r', 'win-x64',
    '-p:Platform=x64',
    '-p:NuGetAudit=false'
)

& dotnet @restoreArguments
if ($LASTEXITCODE -ne 0) {
    $localPackages = Join-Path $env:USERPROFILE '.nuget\packages'
    if (Test-Path -LiteralPath $localPackages) {
        Write-Host 'Online restore failed, retrying from the local NuGet cache...'
        $restoreArguments += @('--source', $localPackages)
        & dotnet @restoreArguments
    }

    if ($LASTEXITCODE -ne 0) {
        throw "dotnet restore failed with exit code $LASTEXITCODE"
    }
}

$publishArguments = @(
    'publish', $project,
    '-c', $Configuration,
    '-r', 'win-x64',
    '--self-contained', 'false',
    '--no-restore',
    '-p:Platform=x64',
    '-p:SelfContained=false',
    '-p:PublishSingleFile=false',
    '-p:EnableMsixTooling=true',
    '-p:DebugType=None',
    '-p:DebugSymbols=false',
    '-p:NuGetAudit=false',
    '-o', $staging
)

& dotnet @publishArguments
if ($LASTEXITCODE -ne 0) {
    throw "dotnet publish failed with exit code $LASTEXITCODE"
}

$publishedExe = Join-Path $staging 'Music.exe'
if (-not (Test-Path -LiteralPath $publishedExe)) {
    throw "Published Music.exe not found at $publishedExe"
}

New-Item -ItemType Directory -Path $output -Force | Out-Null
Copy-Item -Path (Join-Path $staging '*') -Destination $output -Recurse -Force
Remove-Item -LiteralPath $staging -Recurse -Force

# Shipped alongside the app: the end-user notes (LICENSE and
# "Music Launcher.cmd" are copied by hand into the release folder).
$releaseNotes = Join-Path $projectRoot '使用说明.txt'
if (Test-Path -LiteralPath $releaseNotes) {
    Copy-Item -LiteralPath $releaseNotes -Destination $output -Force
}

# Keep the project folder tidy; these are regenerated by the next publish/build.
foreach ($folder in @('bin', 'obj')) {
    $path = Join-Path $projectRoot $folder
    if (Test-Path -LiteralPath $path) {
        Remove-Item -LiteralPath $path -Recurse -Force
    }
}

# The dist folder is exactly what gets zipped: Music.exe, the Windows App SDK
# files it loads from its own folder, and the Assets / language folders.
# Music.exe only runs when the whole folder is kept together.
$expectedRootFiles = @(
    'Music.exe',
    'Music.dll',
    'Music.deps.json',
    'Music.runtimeconfig.json',
    'Music.pri',
    'Microsoft.WindowsAppRuntime.dll',
    'Microsoft.UI.Xaml.Controls.dll',
    'Microsoft.WindowsAppRuntime.pri'
)
$expectedRootFolders = @('Assets', 'language', 'Microsoft.UI.Xaml', 'NpuDetect', 'zh-CN', 'en-us')
foreach ($name in $expectedRootFiles) {
    if (-not (Test-Path -LiteralPath (Join-Path $output $name))) {
        throw "Release folder is missing $name"
    }
}
foreach ($name in $expectedRootFolders) {
    if (-not (Test-Path -LiteralPath (Join-Path $output $name))) {
        throw "Release folder is missing $name\"
    }
}

$rootItems = (Get-ChildItem -LiteralPath $output).Count
$files = Get-ChildItem -LiteralPath $output -Recurse -File
$sizeMb = [math]::Round(($files | Measure-Object Length -Sum).Sum / 1MB, 1)
Write-Host "Published folder: $output ($sizeMb MB, $($files.Count) files, $rootItems items at root)"
